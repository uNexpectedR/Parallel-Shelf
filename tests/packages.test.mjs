test("view stays ui_qml with an empty main, and lists parallel_shelf_core", () => {
  assert.equal(view.name, "parallel_shelf")
  assert.equal(view.type, "ui_qml")
  assert.equal(view.main, undefined)
  assert.ok(view.dependencies.includes("parallel_shelf_core"))
  assert.ok(view.dependencies.includes("storage_module"))
  assert.ok(view.dependencies.includes("delivery_module"))
})

